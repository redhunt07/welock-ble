"""BLE transport for WeLock locks (Nordic UART Service).

Reverse-engineered from the WeLock Android app 4.5.8 and verified against a
real lock (``WeLockA1B2C3``) with an HCI snoop capture.

GATT layout (Nordic UART Service):

* service   ``6e400001-b5a3-f393-e0a9-e50e24dcca9e``
* write     ``6e400002-b5a3-f393-e0a9-e50e24dcca9e``
* notify    ``6e400003-b5a3-f393-e0a9-e50e24dcca9e``

Wire protocol (ASCII frames, 20-byte ATT writes, no checksum):

1. ``U0``                        -> ``55 30 <XX> <YY>``   challenge
2. ``U0 01 <ts:4 LE> <token:8>`` -> ``55 30 <XX> <YY>``   auth accepted
3. ``U1 <token:8> <cmd:5>``      -> ``55 31 <status> <XX> <YY>``

``<cmd>`` is ``AAAA`` + one character generated by the cloud (``p``, ``8``,
``5``, ``x``... were all observed for different commands).

``<status>`` is ``01`` on success and ``00`` on failure.

``<token>`` is **generated by the WeLock cloud**, not by the client: the app
first calls ``POST /api/Command/UnLock``, which answers with
``{"serverID": ..., "command": "<hex>"}``; ``command`` decodes to the complete
``U1`` frame, including the token. The app then reuses that token for the
authentication frame. A random token is therefore rejected with status ``00``,
which is why the frame must be fetched from the cloud before unlocking.

The token is bound to the live challenge: the cloud derives it from
``randomFactor``, which must be the challenge bytes ``<XX> <YY>`` read as a
little endian uint16 (``XX | YY << 8``). Verified against two independent HCI
captures of the official app:

* challenge ``5a 2f`` -> ``randomFactor`` 12122 -> token ``wDAwtdaH`` / ``AAAAp``
* challenge ``a7 44`` -> ``randomFactor`` 17575 -> token ``Q9AQTkn6`` / ``AAAA8``

Passing ``randomFactorData`` makes the server answer with a null token
(``AAAAAAAA``), so it must stay unset. ``battery`` does not influence the token.

The challenge is regenerated by the lock, so the handshake must be repeated on
every connection.

The app keeps the link open only for the duration of the command, so this
transport connects on demand, performs the handshake, sends the command and
disconnects again.
"""

from __future__ import annotations

import asyncio
import logging
import random
import string
import time
from typing import Any, Awaitable, Callable

from bleak import BleakClient, BleakScanner
from bleak.exc import BleakError

try:  # the standalone probe imports this module without Home Assistant
    from homeassistant.core import HomeAssistant
except ImportError:  # pragma: no cover
    HomeAssistant = Any  # type: ignore[assignment,misc]

from .const import (
    BLE_AUTH_FLAG,
    BLE_CHUNK_DELAY,
    BLE_CHUNK_SIZE,
    BLE_CMD_OPEN,
    BLE_NOTIFY_CHAR_UUID,
    BLE_REPLY_CHALLENGE,
    BLE_REPLY_COMMAND,
    BLE_REPLY_TIMEOUT,
    BLE_RETRIES,
    BLE_SERVICE_UUID,
    BLE_STATUS_OK,
    BLE_TOKEN_LEN,
    BLE_WRITE_CHAR_UUID,
)

_LOGGER = logging.getLogger(__name__)

CONNECT_TIMEOUT = 25
SCAN_TIMEOUT = 12
# The lock answers within a few hundred ms; the timeout only guards a dead link.
RESPONSE_TIMEOUT = max(BLE_REPLY_TIMEOUT, 4.0)


class WeLockBLEError(Exception):
    """Raised when the BLE link cannot be established or used."""


def _to_hex(data: bytes | bytearray) -> str:
    return " ".join(f"{byte:02X}" for byte in data)


def new_token() -> bytes:
    """Return a fresh 8 character alphanumeric token (same alphabet as the app)."""
    alphabet = string.ascii_letters + string.digits
    return "".join(random.choice(alphabet) for _ in range(BLE_TOKEN_LEN)).encode()


class WeLockBLE:
    """On-demand BLE link to a WeLock lock."""

    def __init__(self, hass: HomeAssistant | None, address: str, *, pair: bool = False) -> None:
        self._hass = hass
        self._address = address.upper()
        self._pair = pair
        self._cached_device = None

    @property
    def address(self) -> str:
        return self._address

    async def _device(self):
        if self._cached_device is not None:
            return self._cached_device
        if self._hass is not None:
            # Imported lazily so the module also works outside Home Assistant
            # (tools/welock_probe.py passes hass=None).
            from homeassistant.components import bluetooth

            device = bluetooth.async_ble_device_from_address(
                self._hass, self._address, connectable=True
            )
            if device is not None:
                self._cached_device = device
                return device
            _LOGGER.debug("%s not cached, scanning", self._address)

        found = None

        def _on_detect(device, _adv) -> None:
            nonlocal found
            if device.address.upper() == self._address:
                found = device

        for _ in range(3):
            try:
                scanner = BleakScanner(
                    detection_callback=_on_detect, scanning_mode="active"
                )
                await scanner.start()
            except BleakError as err:
                _LOGGER.debug("scanner busy (%s), retrying", err)
                await asyncio.sleep(2)
                continue
            await asyncio.sleep(SCAN_TIMEOUT)
            try:
                await scanner.stop()
            except BleakError as err:
                # BlueZ sometimes reports a stale discovery session; harmless.
                _LOGGER.debug("scanner stop failed (%s), ignoring", err)
            if found is not None:
                self._cached_device = found
                return found

        raise WeLockBLEError(
            f"lock {self._address} not seen by any Bluetooth adapter/proxy"
        )

    async def _connect(self) -> BleakClient:
        device = await self._device()
        client = BleakClient(device, pair=self._pair, timeout=CONNECT_TIMEOUT)
        try:
            await client.connect()
        except (BleakError, asyncio.TimeoutError) as err:
            # BlueZ drops devices from its cache after a while; forget the
            # cached BLEDevice so the next attempt scans again.
            if "not found" in str(err):
                self._cached_device = None
            raise WeLockBLEError(f"cannot connect to {self._address}: {err}") from err
        if not client.is_connected:
            raise WeLockBLEError(f"connection to {self._address} failed")
        _LOGGER.debug("connected to %s", self._address)
        return client

    async def _characteristics(self, client: BleakClient):
        services = client.services
        service = services.get_service(BLE_SERVICE_UUID)
        if service is None:
            raise WeLockBLEError(
                f"service {BLE_SERVICE_UUID} not found on {self._address}"
            )
        write_char = services.get_characteristic(BLE_WRITE_CHAR_UUID)
        notify_char = services.get_characteristic(BLE_NOTIFY_CHAR_UUID)
        if write_char is None or notify_char is None:
            raise WeLockBLEError(
                f"NUS characteristics missing on {self._address} "
                f"(write={write_char}, notify={notify_char})"
            )
        return write_char, notify_char

    async def _write(self, client: BleakClient, write_char: Any, payload: bytes) -> None:
        """Write ``payload`` in 20-byte ATT writes (as the app does).

        Write requests (``response=True``) are used on purpose: on a weak link
        ATT write commands (``response=False``) are silently dropped, while
        write requests are acknowledged by the lock and retried by BlueZ.
        """
        _LOGGER.debug("writing to %s: %s", self._address, _to_hex(payload))
        for offset in range(0, len(payload), BLE_CHUNK_SIZE):
            chunk = payload[offset : offset + BLE_CHUNK_SIZE]
            try:
                await client.write_gatt_char(write_char, chunk, response=True)
            except BleakError as err:
                # Some stacks reject write requests; fall back to write commands.
                _LOGGER.debug(
                    "%s: write request failed (%s), retrying as command",
                    self._address,
                    err,
                )
                await client.write_gatt_char(write_char, chunk, response=False)
            if offset + BLE_CHUNK_SIZE < len(payload):
                await asyncio.sleep(BLE_CHUNK_DELAY)

    async def _exchange(
        self,
        client: BleakClient,
        write_char: Any,
        notifications: list[bytes],
        payload: bytes,
        prefix: bytes,
        timeout: float = RESPONSE_TIMEOUT,
        *,
        resend: bool = True,
    ) -> bytes | None:
        """Send ``payload`` and return the first notification starting with ``prefix``.

        A weak link silently drops some writes, so a write that gets no answer
        is repeated once before giving up.
        """
        for _ in range(2 if resend else 1):
            notifications.clear()
            await self._write(client, write_char, payload)
            deadline = asyncio.get_running_loop().time() + timeout
            while asyncio.get_running_loop().time() < deadline:
                for frame in list(notifications):
                    if frame.startswith(prefix):
                        notifications.remove(frame)
                        return frame
                await asyncio.sleep(0.02)
            _LOGGER.debug(
                "%s: no %s reply to %s, retrying write",
                self._address,
                _to_hex(prefix),
                _to_hex(payload),
            )
        return None

    async def _challenge(
        self,
        client: BleakClient,
        write_char: Any,
        notifications: list[bytes],
    ) -> bytes:
        """Send ``U0`` and return the challenge the lock answers with."""
        challenge = await self._exchange(
            client, write_char, notifications, b"U0", BLE_REPLY_CHALLENGE
        )
        if challenge is None:
            raise WeLockBLEError(f"{self._address} did not answer the challenge")
        if len(challenge) < 4 or challenge[0] != 0x55 or challenge[1] != 0x30:
            raise WeLockBLEError(
                f"{self._address} sent an unexpected challenge: {_to_hex(challenge)}"
            )
        _LOGGER.debug("challenge from %s: %s", self._address, _to_hex(challenge))
        # ``55 30`` is the frame header; the challenge itself is the payload.
        return challenge[2:4]

    async def async_unlock(
        self,
        command: bytes | None = None,
        *,
        command_provider: Callable[[bytes], Awaitable[bytes]] | None = None,
    ) -> dict[str, Any]:
        """Open the lock over BLE.

        ``command_provider`` receives the live challenge and must return the
        complete ``U1`` frame. The WeLock cloud derives the token from the
        challenge: ``POST /api/Command/UnLock`` must be called with
        ``randomFactor`` set to the challenge read as a little endian uint16,
        otherwise the lock rejects the token with status ``00``.

        ``command`` is a pre-built frame (only valid when its token happens to
        match the challenge). Without either, a random token is used, which is
        useful only to probe the link.
        """
        last_error: Exception | None = None
        for attempt in range(1, BLE_RETRIES + 1):
            client = None
            try:
                client = await self._connect()
                write_char, notify_char = await self._characteristics(client)
                notifications: list[bytes] = []
                await client.start_notify(
                    notify_char,
                    lambda _sender, data: notifications.append(bytes(data)),
                )
                challenge = await self._challenge(client, write_char, notifications)
                if command_provider is not None:
                    frame = await command_provider(challenge)
                elif command is not None:
                    frame = command
                else:
                    frame = b"U1" + new_token() + BLE_CMD_OPEN
                if not frame or len(frame) < 2 + BLE_TOKEN_LEN:
                    raise WeLockBLEError(
                        f"invalid unlock frame: {_to_hex(frame or b'')}"
                    )
                token = frame[2 : 2 + BLE_TOKEN_LEN]

                timestamp = int(time.time()).to_bytes(4, "little")
                auth = b"U0" + BLE_AUTH_FLAG + timestamp + token
                ack = await self._exchange(
                    client, write_char, notifications, auth, BLE_REPLY_CHALLENGE
                )
                if ack is None:
                    raise WeLockBLEError(
                        f"{self._address} did not acknowledge the login"
                    )
                # A rejection carries an extra 0x00 status byte; the accepted
                # answer is the bare 4 byte echo of the challenge.
                if len(ack) >= 5:
                    raise WeLockBLEError(
                        f"lock rejected the login (challenge {_to_hex(challenge)})"
                    )
                _LOGGER.debug("auth ack from %s: %s", self._address, _to_hex(ack))
                # The lock needs a moment between the auth ack and the command.
                await asyncio.sleep(BLE_CHUNK_DELAY * 3)
                reply = await self._exchange(
                    client,
                    write_char,
                    notifications,
                    frame,
                    BLE_REPLY_COMMAND,
                )
                if reply is None:
                    raise WeLockBLEError(
                        f"{self._address} did not answer the open command"
                    )
                status = reply[2] if len(reply) > 2 else None
                result = {
                    "raw": reply.hex(),
                    "token": token.decode(),
                    "status": status,
                    "success": status == BLE_STATUS_OK,
                    "attempts": attempt,
                }
                _LOGGER.debug("open reply from %s: %s", self._address, result)
                if result["success"]:
                    return result
                last_error = WeLockBLEError(
                    f"lock rejected the open command (status {status})"
                )
            except (BleakError, asyncio.TimeoutError) as err:
                last_error = WeLockBLEError(f"BLE exchange with {self._address} failed: {err}")
            except WeLockBLEError as err:
                last_error = err
            finally:
                if client is not None:
                    try:
                        await client.disconnect()
                    except (BleakError, asyncio.TimeoutError):
                        pass
            if attempt < BLE_RETRIES:
                _LOGGER.debug(
                    "open attempt %s failed (%s), retrying", attempt, last_error
                )
                self._cached_device = None
                await asyncio.sleep(1)

        raise last_error or WeLockBLEError(f"cannot open {self._address}")

    async def send(self, payload: bytes, *, expect_response: bool = True) -> list[bytes]:
        """Write ``payload`` raw and return the notifications received."""
        client = await self._connect()
        notifications: list[bytes] = []
        try:
            write_char, notify_char = await self._characteristics(client)
            await client.start_notify(
                notify_char,
                lambda _sender, data: notifications.append(bytes(data)),
            )
            await self._write(client, write_char, payload)
            if expect_response:
                await asyncio.sleep(RESPONSE_TIMEOUT)
            await client.stop_notify(notify_char)
        except (BleakError, asyncio.TimeoutError) as err:
            raise WeLockBLEError(f"BLE exchange with {self._address} failed: {err}") from err
        finally:
            try:
                await client.disconnect()
            except (BleakError, asyncio.TimeoutError):
                pass
        return notifications

    async def probe(self, frame: bytes) -> list[bytes]:
        """Send a raw frame and return whatever the lock answers."""
        return await self.send(frame)
